#!/usr/bin/env node
// Writes src-tauri/binaries/THIRD-PARTY-LICENSES.txt: the license texts of
// every Rust crate and npm package that ends up inside the app. MIT, Apache
// and similar licenses ask for their notice to travel with the binary, and
// the packages ship this file (bundle.resources in tauri.conf.json).
//
//   node scripts/third-party-licenses.mjs
//
// Only reads Cargo.lock (through `cargo metadata`, offline when possible) and
// node_modules: no network of its own.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src-tauri/binaries/THIRD-PARTY-LICENSES.txt');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f) && statSync(join(dir, f)).isFile())
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim());
}

// Crates linked into the app: normal dependencies reachable from offbeat.
// Build scripts and dev-dependencies do not ship.
function rustPackages() {
  const triple = execFileSync('rustc', ['-vV'], { encoding: 'utf8' }).match(/^host: (.+)$/m)[1];
  const metadata = JSON.parse(
    execFileSync(
      'cargo',
      ['metadata', '--format-version', '1', '--locked', '--filter-platform', triple],
      { cwd: join(ROOT, 'src-tauri'), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    ),
  );
  const byId = new Map(metadata.packages.map((p) => [p.id, p]));
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const root = metadata.resolve.root;
  const seen = new Set([root]);
  const stack = [root];
  while (stack.length > 0) {
    for (const dep of nodes.get(stack.pop()).deps) {
      const normal = dep.dep_kinds.some((k) => k.kind === null);
      if (normal && !seen.has(dep.pkg)) {
        seen.add(dep.pkg);
        stack.push(dep.pkg);
      }
    }
  }
  seen.delete(root);
  return [...seen].map((id) => {
    const p = byId.get(id);
    return {
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? 'see text' : 'unknown'),
      url: p.repository ?? p.homepage ?? '',
      texts: licenseTexts(dirname(p.manifest_path)),
    };
  });
}

// npm packages bundled into dist/: everything in the lockfile that is not dev-only.
function npmPackages() {
  const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'));
  return Object.entries(lock.packages)
    .filter(([path, e]) => path.startsWith('node_modules/') && !e.dev && !e.devOptional)
    .filter(([path]) => existsSync(join(ROOT, path)))
    .map(([path, e]) => {
      const pkg = JSON.parse(readFileSync(join(ROOT, path, 'package.json'), 'utf8'));
      const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
      return {
        name: pkg.name,
        version: e.version ?? pkg.version,
        license: e.license ?? pkg.license ?? 'unknown',
        url: repo ?? pkg.homepage ?? '',
        texts: licenseTexts(join(ROOT, path)),
      };
    });
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version);
const rust = rustPackages().sort(byName);
const npm = npmPackages().sort(byName);

// Many crates carry identical texts; print each text once with its users.
const users = new Map();
for (const p of [...rust, ...npm]) {
  for (const text of p.texts) {
    if (!users.has(text)) users.set(text, []);
    users.get(text).push(`${p.name} ${p.version}`);
  }
}

const row = (p) => `  ${p.name} ${p.version}  ${p.license}${p.url ? `  ${p.url}` : ''}`;
const missing = [...rust, ...npm].filter((p) => p.texts.length === 0);
const lines = [
  'Offbeat: third-party licenses',
  '',
  'Libraries compiled into Offbeat. The bundled programs (yt-dlp, ffmpeg,',
  'ffprobe, deno) have their own license files next to this one.',
  'Generated by scripts/third-party-licenses.mjs.',
  '',
  `Rust crates (${rust.length})`,
  ...rust.map(row),
  '',
  `npm packages (${npm.length})`,
  ...npm.map(row),
  '',
];
if (missing.length > 0) {
  lines.push(
    'Packages without a license file (their SPDX license above applies):',
    ...missing.map((p) => `  ${p.name} ${p.version}  ${p.license}`),
    '',
  );
}
for (const [text, who] of users) {
  lines.push('='.repeat(78), `Used by: ${who.join(', ')}`, '-'.repeat(78), text, '');
}

writeFileSync(OUT, lines.join('\n'));
console.log(
  `  ✓ THIRD-PARTY-LICENSES.txt (${rust.length} crates, ${npm.length} npm packages, ${users.size} texts)`,
);
